def log_event(line: str):































    clean_line = line.rstrip()































    if not clean_line:































        return































    parse_progress(clean_line)































    formatted = format_user_log(clean_line)































    if formatted:































        timestamp = datetime.now().strftime("%H:%M:%S")































        entry = f"[{timestamp}] {formatted}"































        log_buffer.append(entry)































































def parse_progress(line: str):































    global job_status































































    # 1. Planning stage































    if "PLAN_START" in line or "PHASE_PLAN_START" in line:































        m_tot = re.search(r"scenes\s+(\d+)", line)































        if m_tot:































            job_status["total_scenes"] = int(m_tot.group(1))































        job_status["stage"] = "PLANNING"































        job_status["percent"] = max(job_status["percent"], 8)































        job_status["message"] = "Đang khởi tạo cấu trúc và phân cảnh tập phim..."































































    if "PLAN_BIBLE_START" in line:































        job_status["stage"] = "PLAN_BIBLE"































        job_status["percent"] = max(job_status["percent"], 11)































        job_status["message"] = "Đang xây dựng thế giới & nhân vật (Story Bible)..."































































    if "PLAN_BIBLE_DONE" in line:































        job_status["percent"] = max(job_status["percent"], 12)































        job_status["message"] = "Đã hoàn thành Story Bible! Bắt đầu viết kịch bản chi tiết..."































































    m_pbatch = re.search(r"PLAN_BATCH_START\s+(\d+)/(\d+)", line)































    if m_pbatch:































        cur_b, tot_b = int(m_pbatch.group(1)), int(m_pbatch.group(2))































        m_rng = re.search(r"scenes\s+(\d+)-(\d+)", line)































        rng_txt = f" (Cảnh {m_rng.group(1)}-{m_rng.group(2)})" if m_rng else ""































        pct = 12 + int(((cur_b - 1) / max(1, tot_b)) * 8)































        job_status["percent"] = max(job_status["percent"], pct)































        job_status["message"] = f"Đang viết kịch bản chi tiết đợt {cur_b}/{tot_b}{rng_txt}..."































































    m_pprompt = re.search(r"PLAN_BATCH_PROMPT\s*(.*)", line)































