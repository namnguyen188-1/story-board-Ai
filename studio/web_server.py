def resize_window_win32(width: int = 1400, height: int = 850) -> int:































    """Forces all Storyboard Studio desktop windows to exact width and height (1400x850) on Windows."""































    try:































        import ctypes































        from ctypes import wintypes































        user32 = ctypes.windll.user32































        user32.MoveWindow.argtypes = [wintypes.HWND, ctypes.c_int, ctypes.c_int, ctypes.c_int, ctypes.c_int, wintypes.BOOL]































        user32.MoveWindow.restype = wintypes.BOOL































        user32.ShowWindow.argtypes = [wintypes.HWND, ctypes.c_int]































        user32.ShowWindow.restype = wintypes.BOOL































































        # Ensure we attach to user's interactive desktop if running in an isolated thread or desktop































        try:































            h_desk = user32.OpenDesktopW("Default", 0, False, 0x01FF)































            if h_desk:































                user32.SetThreadDesktop(h_desk)































        except Exception:































            pass































































        WNDENUMPROC = ctypes.WINFUNCTYPE(ctypes.c_int, wintypes.HWND, wintypes.LPARAM)































        found = []































































        def enum_cb(hwnd, lparam):































            if user32.IsWindowVisible(hwnd):































                length = user32.GetWindowTextLengthW(hwnd)































                if length > 0:































                    buff = ctypes.create_unicode_buffer(length + 1)































                    user32.GetWindowTextW(hwnd, buff, length + 1)































                    title = buff.value































                    if any(k.lower() in title.lower() for k in ("storyboard", "studio pro", "127.0.0.1:8765", "phần mềm sản xuất phim")):































                        found.append(hwnd)































            return 1































































        user32.EnumWindows(WNDENUMPROC(enum_cb), 0)































        sw = user32.GetSystemMetrics(0)































        sh = user32.GetSystemMetrics(1)































        x = max(0, (sw - width) // 2)































        y = max(0, (sh - height) // 2)































































        for hwnd in found:































            user32.ShowWindow(hwnd, 9)  # SW_RESTORE (un-maximize)































            user32.MoveWindow(hwnd, x, y, width, height, True)































        return len(found)































    except Exception as e:































        print("[RESIZE_ERROR]", e)































        return 0































































































