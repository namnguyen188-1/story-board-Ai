def resolve_production_episode(series_name: str, ep_num: int):































    """































    Strictly locates the episode directory for a given series name and episode number.































    GUARANTEES 100% EPISODE ISOLATION:































    - If a specific ep_num is requested, NEVER silently falls back to a different episode number!































    - Only falls back to the most recent production if series_name is 'auto'/empty and ep_num <= 1.































    Returns: (resolved_series_name, resolved_ep_num, resolved_ep_dir)































    """































    from series_studio import slug































    ep_dir = None































    ep_num = int(ep_num or 1)































































    # 1. Direct path search if series_name is provided































    if series_name and series_name != "auto":































        candidates = [































            PRODUCTIONS_DIR / series_name / f"episode_{ep_num:03d}",































            PRODUCTIONS_DIR / slug(series_name) / f"episode_{ep_num:03d}",































            PRODUCTIONS_DIR / f"{slug(series_name)}-offline-test" / f"episode_{ep_num:03d}",































            PRODUCTIONS_DIR / slug(series_name + " - Offline Test") / f"episode_{ep_num:03d}",































        ]































        for c in candidates:































            if c.is_dir():































                ep_dir = c































                break































































        # Fuzzy case-insensitive search for series directory































        if not ep_dir and PRODUCTIONS_DIR.exists():































            target_slug = slug(series_name).lower()































            for p_dir in PRODUCTIONS_DIR.iterdir():































                if p_dir.is_dir() and (slug(p_dir.name).lower() == target_slug or p_dir.name.lower() == series_name.lower()):































                    cand = p_dir / f"episode_{ep_num:03d}"































                    if cand.is_dir():































                        ep_dir = cand































                        series_name = p_dir.name































                        break































































        # Fallback if ep_dir was not found for the requested episode number:

        # If ep_num <= 1 (default initial state) and episode_001 does not exist in this series,

        # but other episodes exist (e.g. episode_002), automatically resolve to the latest episode!

        if not ep_dir and ep_num <= 1 and PRODUCTIONS_DIR.exists():

            target_slug = slug(series_name).lower() if series_name else ''

            for p_dir in PRODUCTIONS_DIR.iterdir():

                if p_dir.is_dir() and (slug(p_dir.name).lower() == target_slug or p_dir.name.lower() == str(series_name).lower()):

                    ep_cands = sorted([d for d in p_dir.glob('episode_*') if d.is_dir()], key=lambda d: d.name)

                    if ep_cands:

                        cand = ep_cands[-1]

                        m = re.search(r'episode_(\d+)', cand.name)

                        found_ep = int(m.group(1)) if m else ep_num

                        return p_dir.name, found_ep, cand



        # If a specific series and episode was requested but not found, NEVER hijack with another episode!

        if not ep_dir:

            return series_name, ep_num, None































































        return series_name, ep_num, ep_dir































































    # 2. If series is auto/empty, but ep_num > 1 is requested, search across all series for this exact ep_num































    if (not series_name or series_name == "auto") and ep_num > 1:































        if PRODUCTIONS_DIR.exists():































            for p_dir in PRODUCTIONS_DIR.iterdir():































                if p_dir.is_dir():































                    cand = p_dir / f"episode_{ep_num:03d}"































                    if cand.is_dir():































                        return p_dir.name, ep_num, cand































        return series_name, ep_num, None































































    # 3. Only if completely unconstrained (series is auto and ep_num <= 1), find most recent production































    if not ep_dir:































        recent_prod = None































        latest_mtime = -1































        if PRODUCTIONS_DIR.exists():































            for p_dir in PRODUCTIONS_DIR.iterdir():































                if p_dir.is_dir():































                    for ep_cand in p_dir.glob("episode_*"):































                        if ep_cand.is_dir() and (ep_cand / "plan.json").exists():































                            mt = (ep_cand / "plan.json").stat().st_mtime































                            if mt > latest_mtime:































                                latest_mtime = mt































                                recent_prod = (p_dir.name, ep_cand.name, ep_cand)































        if recent_prod:































            series_name = recent_prod[0]































            ep_dir = recent_prod[2]































            ep_num = int(re.sub(r"\D", "", recent_prod[1]) or 1)































            try:































                pj = json.loads((ep_dir / "plan.json").read_text(encoding="utf-8"))































                if pj.get("config", {}).get("series"):































                    series_name = pj["config"]["series"]































            except Exception:































                pass































































    return series_name, ep_num, ep_dir































































































