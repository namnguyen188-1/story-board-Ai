def _check_update_status():































    """Read and validate the release manifest for the header update indicator."""































    raw = None































    last_exc = None































    urls_to_try = [UPDATE_MANIFEST_URL, UPDATE_FALLBACK_MANIFEST_URL]































    for url in urls_to_try:































        try:































            request = urllib.request.Request(































                url,































                headers={"Cache-Control": "no-cache", "Pragma": "no-cache", "User-Agent": "StoryboardAI-UpdateCheck/1.0"},































            )































            with urllib.request.urlopen(request, timeout=5) as response:































                raw = response.read(65537)































            if raw:































                break































        except Exception as exc:































            last_exc = exc































            continue































































    current = _installed_app_version()































    if raw is None:































        return {































            "ok": False,































            "error": type(last_exc).__name__ if last_exc else "manifest_fetch_failed",































            "current_version": current,































            "latest_version": current,































            "update_available": False,































        }































































    try:































        if len(raw) > 65536:































            raise ValueError("manifest_too_large")































        manifest = json.loads(raw.decode("utf-8"))































        latest = str(manifest.get("version", "")).strip()































        latest_key = _version_key(latest)































        current_key = _version_key(current)































        installer_url = urllib.parse.urlsplit(str(manifest.get("installer", "")))































        installer_bytes = int(manifest.get("bytes", manifest.get("size_bytes", 0)))































        sha256 = str(manifest.get("sha256", ""))































        if latest_key is None or current_key is None:































            raise ValueError("version_unavailable")































        is_allowed_tailscale = (































            installer_url.scheme == "http"































            and installer_url.hostname == UPDATE_ALLOWED_HOST































            and installer_url.port == UPDATE_ALLOWED_PORT































        )































        is_allowed_github = (































            installer_url.scheme == "https"































            and installer_url.hostname in ("github.com", "raw.githubusercontent.com", "objects.githubusercontent.com")































        )































        if not (is_allowed_tailscale or is_allowed_github):































            raise ValueError("installer_host_invalid")































        if installer_bytes < 1000000 or installer_bytes > 2000000000:































            raise ValueError("installer_size_invalid")































        if not re.fullmatch(r"[A-Fa-f0-9]{64}", sha256):































            raise ValueError("installer_hash_invalid")































        return {































            "ok": True,































            "current_version": current,































            "latest_version": latest,































            "update_available": latest_key > current_key,































            "installer_bytes": installer_bytes,































        }































    except Exception as exc:































        return {"ok": False, "error": type(exc).__name__, "current_version": current}































