def _version_key(value):































    """Return a comparable four-part version tuple, or None for invalid input."""































    if not re.fullmatch(r"\s*\d+(?:\.\d+){0,3}\s*", str(value or "")):































        return None































    parts = tuple(int(part) for part in str(value).strip().split("."))































    return parts + (0,) * (4 - len(parts))































































































