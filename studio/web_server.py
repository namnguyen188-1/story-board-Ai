def production_python() -> str:































    """Use the Studio renderer environment, not an unrelated server/launcher Python.































































    The Windows desktop bootstrapper may run this HTTP server with D:\\python.exe,































    which does not necessarily contain OpenCV/NumPy. CLI rendering must use































    Studio/.venv whenever it is present. Keep fallback for packaged installs.































    """































    portable = STUDIO_DIR / "runtime" / "python" / "python.exe"































    if portable.is_file():































        return str(portable)































    bundled = STUDIO_DIR / ".venv" / ("Scripts/python.exe" if os.name=="nt" else "bin/python")































    return str(bundled) if bundled.is_file() else sys.executable































































